"""Print the Homebrew formula for a release, for the tap at Itqan-community/homebrew-tap.

    python scripts/homebrew_formula.py 0.2.0 dist/SHA256SUMS > Formula/itqan.rb

The formula installs the standalone binaries from the GitHub Release (binaries.yml), so
Homebrew users don't need Python. release.yml runs this on every final release.
"""

from pathlib import Path
import sys

REPO = "Itqan-community/itqan-cli"

# Homebrew (os, CPU) -> the binary's os-arch suffix.
PLATFORMS = {
    ("macos", "arm"): "macos-arm64",
    ("macos", "intel"): "macos-x86_64",
    ("linux", "arm"): "linux-arm64",
    ("linux", "intel"): "linux-x86_64",
}

TEMPLATE = """\
# Generated by https://github.com/{repo}/blob/main/scripts/homebrew_formula.py
# on each release. Don't edit by hand.
class Itqan < Formula
  desc "Install and pin Itqan Quranic assets in your project"
  homepage "https://github.com/{repo}"
  version "{version}"
  license "MIT"

  on_macos do
    on_arm do
{macos_arm}
    end
    on_intel do
{macos_intel}
    end
  end

  on_linux do
    on_arm do
{linux_arm}
    end
    on_intel do
{linux_intel}
    end
  end

  def install
    bin.install Dir["itqan-*"].first => "itqan"
  end

  test do
    assert_equal "itqan, version #{{version}}", shell_output("#{{bin}}/itqan --version").strip
  end
end
"""


def parse_checksums(text: str) -> dict[str, str]:
    """`sha256sum` output -> {file name: checksum}."""
    checksums = {}
    for line in text.splitlines():
        if line.strip():
            checksum, name = line.split(maxsplit=1)
            checksums[name.lstrip("*")] = checksum
    return checksums


def render(version: str, checksums: dict[str, str]) -> str:
    blocks = {}
    for (os, cpu), suffix in PLATFORMS.items():
        name = f"itqan-{version}-{suffix}"
        if name not in checksums:
            raise ValueError(f"{name} is missing from SHA256SUMS")
        url = f"https://github.com/{REPO}/releases/download/v{version}/{name}"
        blocks[f"{os}_{cpu}"] = f'      url "{url}"\n      sha256 "{checksums[name]}"'
    return TEMPLATE.format(repo=REPO, version=version, **blocks)


def main(argv: list[str]) -> int:
    if len(argv) != 2:
        print(__doc__, file=sys.stderr)
        return 2
    version, sums_path = argv
    sys.stdout.write(render(version, parse_checksums(Path(sums_path).read_text())))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
