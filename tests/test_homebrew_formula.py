"""Tests for scripts/homebrew_formula.py, which writes the tap's formula on each release."""

import importlib.util
from pathlib import Path

import pytest

_SCRIPT = Path(__file__).resolve().parents[1] / "scripts" / "homebrew_formula.py"
_spec = importlib.util.spec_from_file_location("homebrew_formula", _SCRIPT)
homebrew_formula = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(homebrew_formula)

SUMS = """\
b6b1  itqan-0.2.0-linux-arm64
60c4  itqan-0.2.0-linux-x86_64
bca1  itqan-0.2.0-macos-arm64
7bd3 *itqan-0.2.0-macos-x86_64
f805  itqan-0.2.0-windows-x86_64.exe
3dee  itqan_cli-0.2.0-py3-none-any.whl
"""


def test_render_where_all_binaries_listed_should_pin_each_platform_url_and_checksum():
    # Arrange
    checksums = homebrew_formula.parse_checksums(SUMS)

    # Act
    formula = homebrew_formula.render("0.2.0", checksums)

    # Assert
    base = "https://github.com/Itqan-community/itqan-cli/releases/download/v0.2.0"
    assert 'version "0.2.0"' in formula
    for name, checksum in [
        ("macos-arm64", "bca1"),
        ("macos-x86_64", "7bd3"),
        ("linux-arm64", "b6b1"),
        ("linux-x86_64", "60c4"),
    ]:
        assert f'url "{base}/itqan-0.2.0-{name}"\n      sha256 "{checksum}"' in formula
    assert "windows" not in formula
    assert 'assert_equal "itqan, version #{version}", shell_output("#{bin}/itqan --version").strip' in formula


def test_render_where_binary_missing_should_refuse():
    # Arrange
    checksums = homebrew_formula.parse_checksums(SUMS.replace("  itqan-0.2.0-linux-arm64\n", "  other\n"))

    # Act / Assert
    with pytest.raises(ValueError, match="itqan-0.2.0-linux-arm64"):
        homebrew_formula.render("0.2.0", checksums)


def test_main_where_given_sums_file_should_print_formula(tmp_path: Path, capsys):
    # Arrange
    sums = tmp_path / "SHA256SUMS"
    sums.write_text(SUMS)

    # Act
    code = homebrew_formula.main(["0.2.0", str(sums)])

    # Assert
    assert code == 0
    assert capsys.readouterr().out.startswith("# Generated by")
